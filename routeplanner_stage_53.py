# Project: RoutePlanner
def show_help():
    print("RoutePlanner - Delivery Route Planner")
    print("Usage: routeplanner <command> [options]")
    print()
    print("Commands:")
    print("  add-stop <name> <address> [distance_km]   Add a delivery stop")
    print("  list-stops                                 Show all registered stops")
    print("  schedule <stop_name> <time>                Set the delivery time")
    print("  list-schedule                              Show all scheduled stops")
    print("  distance <stop_a> <stop_b>                 Show distance between stops")
    print("  mark-done <stop_name> [note]               Mark a stop as completed")
    print("  list-dones                                 Show completed stops")
    print("  help                                       Show this help message")
    print("  exit                                       Quit the planner")
    print()
    print("Examples:")
    print("  routeplanner add-stop Home 123 Main St 0")
    print("  routeplanner add-stop Office 456 Oak Ave 5.2")
    print("  routeplanner schedule Office 14:30")
    print("  routeplanner distance Home Office")
    print("  routeplanner mark-done Office Delivered to reception")
    print("  routeplanner help")
